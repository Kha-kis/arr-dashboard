hash_file() {
	file=$1
	if command -v sha256sum >/dev/null 2>&1; then
		output=$(sha256sum "$file") || return 1
	elif command -v shasum >/dev/null 2>&1; then
		output=$(shasum -a 256 "$file") || return 1
	else
		return 2
	fi
	digest=${output%%[[:space:]]*}
	is_sha256 "$digest" || return 1
	printf '%s\n' "$digest"
}
